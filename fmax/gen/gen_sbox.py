#!/usr/bin/env python3
"""gen_sbox.py - emit rtl/aes_sbox_fn.svh with two S-box styles, verified exhaustively here.
  LUT   : 256-entry case tables (forward, inverse) - synthesis tool chooses the logic.
  TOWER : composite field GF((2^4)^2), one shared GF(2^8) inverter for enc and dec
          (classic area-saving structure). Isomorphism found by search, not typed in.
Byte convention: plain 8-bit values (bit i = coefficient of x^i, AES poly 0x11B)."""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "..", "golden"))
from golden_xts import SBOX, INV_SBOX, _gmul

# ---- GF(16), p(z) = z^4 + z + 1
def g16mul(a, b):
    r = 0
    for i in range(4):
        if b >> i & 1: r ^= a << i
    for i in (6, 5, 4):
        if r >> i & 1: r ^= 0b10011 << (i - 4)
    return r & 0xF
G16INV = [0] + [next(y for y in range(1, 16) if g16mul(x, y) == 1) for x in range(1, 16)]
# ---- GF((2^4)^2) = GF(16)[Y]/(Y^2 + Y + LAM); element = (hi << 4) | lo  meaning hi*Y + lo
LAM = next(l for l in range(1, 16) if all(g16mul(t, t) ^ t != l for t in range(16)))
def cmul(a, b):
    a1, a0, b1, b0 = a >> 4, a & 15, b >> 4, b & 15
    hh = g16mul(a1, b1)
    return ((hh ^ g16mul(a1, b0) ^ g16mul(a0, b1)) << 4) | (g16mul(a0, b0) ^ g16mul(hh, LAM))
def cinv(a):
    a1, a0 = a >> 4, a & 15
    d = g16mul(g16mul(a1, a1), LAM) ^ g16mul(a1, a0) ^ g16mul(a0, a0)
    di = G16INV[d]
    return (g16mul(a1, di) << 4) | g16mul(a0 ^ a1, di)
# ---- isomorphism: find h in composite field with m(h) = 0, m = AES poly x^8+x^4+x^3+x+1
def cpow(a, n):
    r = 1
    for _ in range(n): r = cmul(r, a)
    return r
H = next(h for h in range(2, 256) if cpow(h, 8) ^ cpow(h, 4) ^ cpow(h, 3) ^ h ^ 1 == 0)
COLS = [cpow(H, i) for i in range(8)]              # phi(x^i)
def lin(cols, v): 
    r = 0
    for i in range(8):
        if v >> i & 1: r ^= cols[i]
    return r
phi = lambda v: lin(COLS, v)
PHI_INV_COLS = [next(x for x in range(256) if phi(x) == 1 << i) for i in range(8)]
phi_inv = lambda v: lin(PHI_INV_COLS, v)
aff = lambda b: b ^ ((b << 1 | b >> 7) & 255) ^ ((b << 2 | b >> 6) & 255) ^ ((b << 3 | b >> 5) & 255) ^ ((b << 4 | b >> 4) & 255)
AFF_INV_COLS = [next(x for x in range(256) if aff(x) == 1 << i) for i in range(8)]
aff_inv = lambda v: lin(AFF_INV_COLS, v)
# fused maps
M_ENC_IN   = [phi(1 << i) for i in range(8)]                       # x -> phi(x)
M_DEC_IN   = [phi(aff_inv(1 << i)) for i in range(8)]              # x -> phi(A^-1 x) ^ C_DEC_IN
C_DEC_IN   = phi(aff_inv(0x63))
M_ENC_OUT  = [aff(phi_inv(1 << i)) for i in range(8)]              # y -> A phi^-1 y ^ 0x63
M_DEC_OUT  = [phi_inv(1 << i) for i in range(8)]                   # y -> phi^-1 y
def tower_sbox(x, dec):
    t = (lin(M_DEC_IN, x) ^ C_DEC_IN) if dec else lin(M_ENC_IN, x)
    y = cinv(t)                                                    # cinv(0) = 0 as AES needs
    return lin(M_DEC_OUT, y) if dec else (lin(M_ENC_OUT, y) ^ 0x63)
assert all(tower_sbox(x, 0) == SBOX[x] and tower_sbox(x, 1) == INV_SBOX[x] for x in range(256)), "tower mismatch"

def rows(cols):  # row masks: out bit r = XOR of in bits i where cols[i] has bit r
    return [sum(((cols[i] >> r) & 1) << i for i in range(8)) for r in range(8)]
def sv_matrix(name, cols):
    L = [f"  function automatic logic [7:0] {name}(input logic [7:0] x);"]
    for r, m in enumerate(rows(cols)):
        L.append(f"    {name}[{r}] = ^(x & 8'h{m:02x});")
    L.append("  endfunction")
    return L

out = ["// AUTO-GENERATED by gen/gen_sbox.py - do not edit. Verified for all 256 inputs in Python.",
       f"// Tower field: GF(16) p(z)=z^4+z+1, Y^2+Y+lambda with lambda=4'h{LAM:x}, iso root h=8'h{H:02x}",
       "package aes_sbox_pkg;"]
out += ["  // ---------------- LUT style", "  function automatic logic [7:0] sbox_lut(input logic [7:0] x);", "    case (x)"]
out += [f"      8'h{i:02x}: sbox_lut = 8'h{SBOX[i]:02x};" for i in range(256)]
out += ["      default: sbox_lut = 8'h00;", "    endcase", "  endfunction",
        "  function automatic logic [7:0] isbox_lut(input logic [7:0] x);", "    case (x)"]
out += [f"      8'h{i:02x}: isbox_lut = 8'h{INV_SBOX[i]:02x};" for i in range(256)]
out += ["      default: isbox_lut = 8'h00;", "    endcase", "  endfunction"]
out += ["  // ---------------- TOWER style",
        "  function automatic logic [3:0] g16mul(input logic [3:0] a, input logic [3:0] b);",
        "    logic [6:0] r; r = 7'd0;",
        "    for (int i = 0; i < 4; i++) if (b[i]) r = r ^ ({3'b0, a} << i);",
        "    if (r[6]) r = r ^ 7'b1001100;", "    if (r[5]) r = r ^ 7'b0100110;", "    if (r[4]) r = r ^ 7'b0010011;",
        "    return r[3:0];", "  endfunction",
        "  function automatic logic [3:0] g16inv(input logic [3:0] a);", "    case (a)"]
out += [f"      4'h{i:x}: g16inv = 4'h{G16INV[i]:x};" for i in range(16)]
out += ["      default: g16inv = 4'h0;", "    endcase", "  endfunction",
        "  function automatic logic [7:0] g256inv(input logic [7:0] a);   // composite-field inverse",
        "    logic [3:0] a1, a0, d, di;", "    a1 = a[7:4]; a0 = a[3:0];",
        f"    d  = g16mul(g16mul(a1, a1), 4'h{LAM:x}) ^ g16mul(a1, a0) ^ g16mul(a0, a0);",
        "    di = g16inv(d);", "    return {g16mul(a1, di), g16mul(a0 ^ a1, di)};", "  endfunction"]
out += sv_matrix("map_enc_in", M_ENC_IN) + sv_matrix("map_dec_in", M_DEC_IN)
out += sv_matrix("map_enc_out", M_ENC_OUT) + sv_matrix("map_dec_out", M_DEC_OUT)
out += ["  function automatic logic [7:0] sbox_tower(input logic [7:0] x);",
        "    return map_enc_out(g256inv(map_enc_in(x))) ^ 8'h63;", "  endfunction",
        "  // shared inverter: dec=0 -> S-box, dec=1 -> inverse S-box",
        "  function automatic logic [7:0] sbox_tower_ed(input logic [7:0] x, input logic dec);",
        "    logic [7:0] t, y;",
        f"    t = dec ? (map_dec_in(x) ^ 8'h{C_DEC_IN:02x}) : map_enc_in(x);",
        "    y = g256inv(t);", "    return dec ? map_dec_out(y) : (map_enc_out(y) ^ 8'h63);", "  endfunction",
        "endpackage"]
path = os.path.join(os.path.dirname(__file__), "..", "rtl", "aes_sbox_pkg.sv")
open(path, "w").write("\n".join(out) + "\n")
# emit exhaustive expected table for the SV self-check
open(os.path.join(os.path.dirname(__file__), "..", "tb", "sbox_expect.hex"), "w").write(
    "\n".join(f"{SBOX[i]:02x}{INV_SBOX[i]:02x}" for i in range(256)) + "\n")
print(f"lambda={LAM:x} h={H:02x}  tower S-box and inverse S-box: 256/256 match golden (Python)")
